import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const [, , reviewsDirectory = "data/reviews", outputPath = "src/catalog-reviewed-generated.js"] = process.argv;
let entries = [];
try {
  entries = (await readdir(reviewsDirectory, { withFileTypes: true }))
    .filter((entry) => entry.isFile() && /^\d{4}\.json$/.test(entry.name))
    .map((entry) => entry.name)
    .sort((left, right) => Number(right.slice(0, 4)) - Number(left.slice(0, 4)));
} catch (error) {
  if (error.code !== "ENOENT") throw error;
}

const reviews = [];
for (const fileName of entries) {
  const payload = JSON.parse(await readFile(path.join(reviewsDirectory, fileName), "utf8"));
  validateYearPayload(payload, fileName);
  reviews.push(payload);
}

const records = reviews.flatMap((payload) => payload.problems);
const completedYears = reviews.map((payload) => Number(payload.year)).sort((a, b) => b - a);
let nextYear = null;
for (let year = 2023; year >= 1962; year -= 1) {
  if (!completedYears.includes(year)) {
    nextYear = year;
    break;
  }
}

const output = `// Generated by scripts/build-reviewed-overlays.mjs. Do not edit by hand.\n` +
  `const PUTNAM_AUTOMATED_REVIEWS = ${JSON.stringify(Object.fromEntries(records.map((record) => [record.id, record])))};\n` +
  `for (const [id, review] of Object.entries(PUTNAM_AUTOMATED_REVIEWS)) {\n` +
  `  const problem = window.PUTNAM_CATALOG?.find((item) => item.id === id);\n` +
  `  if (problem) Object.assign(problem, review);\n` +
  `}\n` +
  `window.PUTNAM_AUTOMATED_REVIEW_PROGRESS = ${JSON.stringify({
    completed_years: completedYears,
    next_year: nextYear,
    analyzed_problem_count: records.length,
  })};\n`;

await writeFile(outputPath, output, "utf8");
console.log(`Built ${records.length} automated solution analyses across ${completedYears.length} years.`);

function validateYearPayload(payload, fileName) {
  if (!Number.isInteger(Number(payload.year))) throw new Error(`${fileName} has no valid year.`);
  if (!Array.isArray(payload.problems) || !payload.problems.length) throw new Error(`${fileName} has no problem analyses.`);
  const expectedPrefix = `putnam_${payload.year}_`;
  for (const problem of payload.problems) {
    if (!String(problem.id || "").startsWith(expectedPrefix)) throw new Error(`${fileName} contains a mismatched id.`);
    if (problem.review_status !== "solution_analyzed") throw new Error(`${problem.id} must be labeled solution_analyzed.`);
    if (!Array.isArray(problem.primary_techniques) || problem.primary_techniques.length < 2) throw new Error(`${problem.id} lacks primary techniques.`);
    if (!Array.isArray(problem.technique_evidence) || problem.technique_evidence.length < 2) throw new Error(`${problem.id} lacks evidence.`);
    if (String(problem.key_observation || "").length < 80) throw new Error(`${problem.id} lacks a key observation.`);
    if (String(problem.solution_architecture || "").length < 120) throw new Error(`${problem.id} lacks solution architecture.`);
  }
}
